-- Instagram credentials stay server-side; the frontend has no table access.
CREATE TABLE IF NOT EXISTS instagram_oauth_states (
    state_hash TEXT PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS instagram_connections (
    user_id UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    instagram_user_id TEXT NOT NULL UNIQUE,
    username TEXT NOT NULL,
    name TEXT,
    account_type TEXT,
    profile_picture_url TEXT,
    biography TEXT,
    followers_count INTEGER NOT NULL DEFAULT 0,
    follows_count INTEGER NOT NULL DEFAULT 0,
    media_count INTEGER NOT NULL DEFAULT 0,
    encrypted_access_token TEXT NOT NULL,
    token_expires_at TIMESTAMPTZ NOT NULL,
    token_updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    discoverable BOOLEAN NOT NULL DEFAULT FALSE,
    share_insights BOOLEAN NOT NULL DEFAULT FALSE,
    last_synced_at TIMESTAMPTZ,
    sync_status TEXT NOT NULL DEFAULT 'CONNECTED',
    last_sync_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_instagram_connections_discovery
    ON instagram_connections (discoverable, followers_count DESC);

CREATE TABLE IF NOT EXISTS instagram_analytics_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES instagram_connections(user_id) ON DELETE CASCADE,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    metrics_json JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_instagram_analytics_user_time
    ON instagram_analytics_snapshots (user_id, captured_at DESC);

CREATE TABLE IF NOT EXISTS instagram_media_snapshots (
    media_id TEXT PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES instagram_connections(user_id) ON DELETE CASCADE,
    media_type TEXT,
    permalink TEXT,
    thumbnail_url TEXT,
    published_at TIMESTAMPTZ,
    metrics_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_instagram_media_user_time
    ON instagram_media_snapshots (user_id, published_at DESC);

-- Supabase clients must never read OAuth states, tokens, or analytics snapshots directly.
ALTER TABLE instagram_oauth_states ENABLE ROW LEVEL SECURITY;
ALTER TABLE instagram_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE instagram_analytics_snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE instagram_media_snapshots ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON instagram_oauth_states, instagram_connections,
    instagram_analytics_snapshots, instagram_media_snapshots FROM anon, authenticated;
REVOKE ALL ON SEQUENCE instagram_analytics_snapshots_id_seq FROM anon, authenticated;
